CREATE TABLE itinerary (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dedup_key      TEXT          NOT NULL,
    origin         VARCHAR(3)    NOT NULL,
    destination    VARCHAR(3)    NOT NULL,
    carrier        VARCHAR(2)    NOT NULL,
    price          NUMERIC(12,2) NOT NULL,
    currency       VARCHAR(3)    NOT NULL,
    departure_time TIMESTAMPTZ   NOT NULL,
    arrival_time   TIMESTAMPTZ   NOT NULL,
    stops          INT           NOT NULL,
    source         VARCHAR(16)   NOT NULL,
    legs           JSONB         NOT NULL,
    ingested_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ux_itinerary_dedup ON itinerary (dedup_key);
CREATE INDEX ix_itinerary_od_price ON itinerary (origin, destination, price, id);
CREATE INDEX ix_itinerary_carrier_price ON itinerary (carrier, price, id);
CREATE INDEX ix_itinerary_price ON itinerary (price, id);
